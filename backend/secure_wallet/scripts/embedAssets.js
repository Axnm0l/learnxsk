const fs = require('fs');
const path = require('path');

// Dynamically resolve root from backend/secure_wallet/scripts -> root
const rootDir = path.resolve(__dirname, '../../..');
const distDir = path.join(rootDir, 'frontend/dist');
const outputFile = path.join(rootDir, 'backend/src/embeddedAssets.ts');

if (!fs.existsSync(distDir)) {
  console.error('Error: frontend/dist does not exist. Run npm run build in frontend first.');
  process.exit(1);
}

const html = fs.readFileSync(path.join(distDir, 'index.html'), 'utf-8');
const assetsDir = path.join(distDir, 'assets');
const assetFiles = fs.readdirSync(assetsDir);

const assetMap = {};
for (const file of assetFiles) {
  const filePath = path.join(assetsDir, file);
  const content = fs.readFileSync(filePath, 'utf-8');
  const contentType = file.endsWith('.css')
    ? 'text/css; charset=UTF-8'
    : file.endsWith('.js')
    ? 'application/javascript; charset=UTF-8'
    : 'application/octet-stream';

  assetMap[`/assets/${file}`] = {
    contentType,
    content: Buffer.from(content).toString('base64')
  };
}

const tsContent = `// Autogenerated embedded assets for LearnXSK standalone executable
export interface EmbeddedAsset {
  contentType: string;
  base64: string;
}

export const EMBEDDED_HTML: string = ${JSON.stringify(html)};

export const EMBEDDED_ASSETS: Record<string, EmbeddedAsset> = {
${Object.entries(assetMap)
  .map(([k, v]) => `  ${JSON.stringify(k)}: { contentType: ${JSON.stringify(v.contentType)}, base64: ${JSON.stringify(v.content)} }`)
  .join(',\n')}
};

export function getEmbeddedAsset(urlPath: string): { contentType: string; buffer: Buffer } | null {
  if (urlPath === '/' || urlPath === '/index.html' || urlPath === '') {
    return {
      contentType: 'text/html; charset=UTF-8',
      buffer: Buffer.from(EMBEDDED_HTML, 'utf-8')
    };
  }

  const asset = EMBEDDED_ASSETS[urlPath];
  if (asset) {
    return {
      contentType: asset.contentType,
      buffer: Buffer.from(asset.base64, 'base64')
    };
  }

  return null;
}
`;

fs.writeFileSync(outputFile, tsContent, 'utf-8');
console.log('✅ [Secure Wallet] Generated embeddedAssets.ts with frontend bundle.');
